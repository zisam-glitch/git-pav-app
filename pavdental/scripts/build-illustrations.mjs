#!/usr/bin/env node
// Builds the app's illustrations from the Streamline "New York" SVGs exported
// from the Pav Dental Figma file (assets/illustrations/source/*.svg).
//
// Each source is a flat list of <path d fill>. This script drops the grey
// artboard background, rounds coordinates to one decimal (the art is drawn on
// a 154pt board, so that is invisible), and swaps every Streamline colour for
// a token name from `illustrationColors` in src/theme/colors.ts. The component
// fills those tokens in at runtime, so the art always follows the app palette.
//
// Usage: node scripts/build-illustrations.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "assets/illustrations/source");
const outDir = join(root, "src/components/illustrations/art");

// Streamline New York colour → illustrationColors token.
const COLOUR_TOKENS = {
  black: "line",
  white: "paper",
  "#F5F5F5": "paper",
  "#FF4848": "accent",
  "#43F7B2": "accent",
  "#A982F4": "accentDeep",
  "#2755A0": "deep",
  "#77751E": "leaf",
  "#C0C195": "sage",
  "#D5E04F": "lime",
  "#78B5FF": "mint",
  "#CCEAFF": "mist",
  "#E6DEFF": "mist",
  "#FFC431": "sun",
  "#F7DA31": "sun",
  "#FFF0B3": "cream",
  "#FFD2D2": "skinLight",
  "#FC9070": "skinMid",
  "#9E647B": "skinDeep",
};

const round = (d) => d.replace(/-?\d*\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));

mkdirSync(outDir, { recursive: true });
const names = [];
for (const file of readdirSync(srcDir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(srcDir, file), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 154 154";
  const paths = [];
  for (const [, attrs] of svg.matchAll(/<path([^>]*)\/?>/g)) {
    const d = attrs.match(/ d="([^"]+)"/)?.[1];
    const fill = attrs.match(/ fill="([^"]+)"/)?.[1];
    if (!d || !fill || fill === "none") continue;
    const token = COLOUR_TOKENS[fill] ?? COLOUR_TOKENS[fill.toUpperCase()];
    if (!token) throw new Error(`${file}: no token for colour ${fill}`);
    paths.push(`<path d="${round(d)}" fill="{${token}}"/>`);
  }
  const name = basename(file, ".svg");
  const xml = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${paths.join("")}</svg>`;
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by scripts/build-illustrations.mjs from assets/illustrations/source/${file}. Do not edit.\nexport default ${JSON.stringify(xml)};\n`,
  );
  names.push(name);
  console.log(`${name}: ${paths.length} paths, ${(xml.length / 1024).toFixed(1)} KB`);
}
console.log(`${names.length} illustrations → ${outDir}`);
