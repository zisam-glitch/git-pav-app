#!/usr/bin/env node
// Builds docs/redesign/website/tracking.md from the per-page files in docs/redesign/website/pages/.
// Run from the repo root:  node docs/redesign/website/build-tracking.mjs
// Agents edit their own page file only; this script is the only writer of tracking.md.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pagesDir = join(here, "pages");
const GROUP_ORDER = ["F1", "A1", "S1", "S2", "S3", "S4", "P1", "C1", "SH"];

const pages = readdirSync(pagesDir)
  .filter((f) => f.endsWith(".md"))
  .map((file) => {
    const text = readFileSync(join(pagesDir, file), "utf8");
    const title = (text.match(/^# (.+)$/m) || [])[1] || file;
    const group = (text.match(/Agent group: \*\*(.+?)\*\*/) || [])[1] || "?";
    const routes = (text.match(/^- Route\(s\): (.+)$/m) || [])[1] || "";
    const sectionBlock = (text.split(/^## Sections$/m)[1] || "").split(/^## /m)[0];
    const rows = sectionBlock
      .split("\n")
      .filter((l) => /^\| \d+ \|/.test(l))
      .map((l) => l.split("|").slice(1, -1).map((c) => c.trim()));
    const count = (s) => rows.filter((r) => r[4] === s).length;
    const images = ((text.split(/^## Images needed \(Google Flow\)$/m)[1] || "").split(/^## /m)[0] || "")
      .split("\n")
      .filter((l) => l.startsWith("|") && !/^\|[-| ]+\|$/.test(l) && !/^\| Slot /.test(l) && !/\|\s*done\s*\|\s*$/i.test(l)).length;
    return { file, slug: file.replace(/\.md$/, ""), title, group, routes, rows, images, n: { todo: count("todo"), built: count("built"), verified: count("verified"), blocked: count("blocked") } };
  })
  .sort((a, b) => GROUP_ORDER.indexOf(a.group) - GROUP_ORDER.indexOf(b.group) || a.title.localeCompare(b.title));

const total = pages.reduce((a, p) => ({ sections: a.sections + p.rows.length, todo: a.todo + p.n.todo, built: a.built + p.n.built, verified: a.verified + p.n.verified, blocked: a.blocked + p.n.blocked, images: a.images + p.images }), { sections: 0, todo: 0, built: 0, verified: 0, blocked: 0, images: 0 });

let md = `# Website redesign tracking (Hims style)

Generated by \`node docs/redesign/website/build-tracking.mjs\` from the per-page files in [pages/](pages/). **Do not edit this file by hand**: edit the page file, then run the script. Design contract: [hims-design-system.md](hims-design-system.md). Agent rules: [AGENT-BRIEF.md](AGENT-BRIEF.md).

Reference sources: the saved Hims homepage (owner's zip), Hims screens and sections on Mobbin (the Hims web app: https://mobbin.com/apps/hims-web-7a66441c-98ab-47f0-9a93-11025e0a2628/5afd08ee-f6ed-4a9b-8947-143658d96058/screens). Words come from the live site (www.pavdental.com) as recorded in \`website/seo/live-text/\`.

Status meaning: \`todo\` not started, \`built\` redesigned but not yet compared with its reference, \`verified\` compared with the reference at 1440 and 390 and the differences fixed, \`blocked\` needs a decision.

## Progress

| Group | Page | Route(s) | Sections | verified | built | todo | blocked | Images to make |
|---|---|---|---|---|---|---|---|---|
${pages.map((p) => `| ${p.group} | [${p.title}](pages/${p.file}) | ${p.routes} | ${p.rows.length} | ${p.n.verified} | ${p.n.built} | ${p.n.todo} | ${p.n.blocked} | ${p.images} |`).join("\n")}
| | **Total** | | **${total.sections}** | **${total.verified}** | **${total.built}** | **${total.todo}** | **${total.blocked}** | **${total.images}** |

`;

for (const p of pages) {
  md += `## ${p.title}\n\nGroup ${p.group} · ${p.routes} · [page file](pages/${p.file})\n\n| # | Section | Reference | Status | 1440 | 390 | Copy | Notes |\n|---|---|---|---|---|---|---|---|\n`;
  // page files link screenshots as ../shots/...; tracking.md sits one level up
  const fix = (cell) => cell.replaceAll("](../shots/", "](shots/");
  for (const r of p.rows) md += `| ${r[0]} | ${r[1]} | ${fix(r[3])} | ${r[4]} | ${fix(r[5])} | ${fix(r[6])} | ${r[7]} | ${r[8]} |\n`;
  md += "\n";
}
writeFileSync(join(here, "tracking.md"), md);
console.log(`tracking.md: ${pages.length} pages, ${total.sections} sections (verified ${total.verified}, built ${total.built}, todo ${total.todo}, blocked ${total.blocked}), ${total.images} images to make`);
